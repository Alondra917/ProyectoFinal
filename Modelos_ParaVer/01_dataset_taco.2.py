# 4. Cargar anotaciones y confirmar los nombres de categoría
import json
from collections import Counter

with open(f'{TACO_DIR}/annotations.json') as f:
    data = json.load(f)

cats = {c['id']: c['name'] for c in data['categories']}
imgs = {im['id']: im for im in data['images']}
print(Counter(cats[a['category_id']] for a in data['annotations']).most_common(15))
