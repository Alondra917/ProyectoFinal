# 5. Recortes por bounding box: margen, cuadrado, descartar < 64 px
from PIL import Image, ImageOps

CLASES = {
    'Cigarette': 'colilla',
    'Clear plastic bottle': 'botella_plastico',
    'Plastic bottle cap': 'tapa_botella',
}
# Clases a generar en esta corrida. Las demás no se tocan (así no se regeneran
# recortes que hayas borrado a mano). Pon None para generar todas desde cero.
PROCESAR = ['tapa_botella']
MARGEN = 0.25     # el cuadrado mide max(ancho, alto) * (1 + MARGEN)
MIN_LADO = 64     # se descarta el recorte si su lado final es menor a esto
MAX_LADO = 512    # se reduce si es mayor (ahorra espacio en Drive; el modelo usa 224)

def abrir_imagen(ruta, ancho_json, alto_json):
    img = Image.open(ruta)
    if img.size != (ancho_json, alto_json):
        girada = ImageOps.exif_transpose(img)
        if girada.size == (ancho_json, alto_json):
            img = girada
        else:
            return None   # tamaño no coincide con el JSON: no se recorta a ciegas
    return img.convert('RGB')

def recorte_cuadrado(img, bbox):
    x, y, bw, bh = bbox
    W, H = img.size
    lado = min(max(bw, bh) * (1 + MARGEN), W, H)
    cx, cy = x + bw / 2, y + bh / 2
    x0 = min(max(cx - lado / 2, 0), W - lado)
    y0 = min(max(cy - lado / 2, 0), H - lado)
    return img.crop((round(x0), round(y0), round(x0 + lado), round(y0 + lado)))

resumen = Counter()
for ann in data['annotations']:
    nombre = cats[ann['category_id']]
    if nombre not in CLASES:
        continue
    clase = CLASES[nombre]
    if PROCESAR is not None and clase not in PROCESAR:
        continue
    salida = f"{RECORTES}/{clase}/{ann['image_id']}_{ann['id']}.jpg"
    if os.path.exists(salida):
        resumen[clase + ' (ya existía)'] += 1
        continue
    info = imgs[ann['image_id']]
    ruta = f"{TACO_DIR}/{info['file_name']}"
    if not os.path.exists(ruta):
        resumen[clase + ' sin archivo'] += 1
        continue
    img = abrir_imagen(ruta, info['width'], info['height'])
    if img is None:
        resumen[clase + ' tamaño no coincide'] += 1
        continue
    rec = recorte_cuadrado(img, ann['bbox'])
    if rec.size[0] < MIN_LADO:
        resumen[clase + ' descartado <64px'] += 1
        continue
    if rec.size[0] > MAX_LADO:
        rec = rec.resize((MAX_LADO, MAX_LADO), Image.LANCZOS)
    os.makedirs(f'{RECORTES}/{clase}', exist_ok=True)
    rec.save(salida, quality=92)
    resumen[clase + ' guardado'] += 1

for k, v in sorted(resumen.items()):
    print(k, v)

