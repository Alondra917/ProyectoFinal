# 4. Tope por clase y partición por grupos (estratificada, semilla fija)
rng = random.Random(SEED)
particion = {}   # clase -> {'train': [...], 'val': [...], 'test': [...]}

for clase in class_names:
    grupos = {}
    for ruta, g in datos[clase]:
        grupos.setdefault(g, []).append(ruta)
    ids = sorted(grupos)
    rng.shuffle(ids)
    elegidos, total = [], 0
    tope = MAX_OTRO if clase == 'otro' else MAX_POR_CLASE
    for g in ids:
        if total >= tope:
            break
        elegidos.append(g)
        total += len(grupos[g])
    out = {'train': [], 'val': [], 'test': []}
    acumulado = 0
    for g in elegidos:
        frac = acumulado / total
        s = 'train' if frac < PROP[0] else ('val' if frac < PROP[0] + PROP[1] else 'test')
        out[s] += grupos[g]
        acumulado += len(grupos[g])
    particion[clase] = out

print(f"{'clase':18s} train  val  test")
