# 10. Exportar tres variantes de TFLite y comparar tamaño y exactitud en VALIDACIÓN
def exportar(nombre, ajustar=None):
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    if ajustar:
        ajustar(conv)
    contenido = conv.convert()
    with open(f'{SALIDA}/modelo_{nombre}.tflite', 'wb') as f:
        f.write(contenido)
    return contenido

def ajuste_f16(c):
    c.optimizations = [tf.lite.Optimize.DEFAULT]
    c.target_spec.supported_types = [tf.float16]      # pesos en float16 (~mitad de tamaño)

def ajuste_int8(c):
    c.optimizations = [tf.lite.Optimize.DEFAULT]      # cuantización dinámica: pesos en int8 (~cuarta parte)

def exactitud_tflite(contenido, X, y):
    it = tf.lite.Interpreter(model_content=contenido)
    it.allocate_tensors()
    e, s = it.get_input_details()[0], it.get_output_details()[0]
    aciertos = 0
    for i in range(len(X)):
        it.set_tensor(e['index'], X[i:i + 1].astype('float32'))
        it.invoke()
        aciertos += int(it.get_tensor(s['index'])[0].argmax() == y[i])
    return aciertos / len(X)

variantes = {'f32': exportar('f32'), 'f16': exportar('f16', ajuste_f16), 'int8': exportar('int8', ajuste_int8)}
print('Keras, exactitud en validación:', round(float((model.predict(Xva.astype('float32'), verbose=0).argmax(1) == yva).mean()), 3))
for nombre, contenido in variantes.items():
    print(f'{nombre}: {len(contenido) / 1e6:.1f} MB | exactitud en validación {exactitud_tflite(contenido, Xva, yva):.3f}')

