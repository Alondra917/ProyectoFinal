# 5. Cargar imágenes: EXIF, recorte cuadrado central y 224x224
import tensorflow as tf
from PIL import Image, ImageOps

def cargar(ruta):
    img = ImageOps.exif_transpose(Image.open(ruta)).convert('RGB')
    w, h = img.size
    lado = min(w, h)
    x0, y0 = (w - lado) // 2, (h - lado) // 2
    img = img.crop((x0, y0, x0 + lado, y0 + lado))
    arr = np.asarray(img, dtype=np.float32)
    arr = tf.image.resize(arr[None], (IMG, IMG), method='bilinear')[0].numpy()
    return np.clip(np.rint(arr), 0, 255).astype('uint8')

def armar(pares):
    X, y, ilegibles = [], [], []
    for ruta, idx in pares:
        try:
            X.append(cargar(ruta)); y.append(idx)
        except Exception as e:
            ilegibles.append((ruta, str(e)[:60]))
    if ilegibles:
        print('No se pudieron leer', len(ilegibles), 'archivos, ejemplo:', ilegibles[0])
    return np.stack(X), np.array(y)

def pares_de(conjunto):
    return [(r, i) for i, c in enumerate(class_names) for r in particion[c][conjunto]]

Xtr, ytr = armar(pares_de('train'))
Xva, yva = armar(pares_de('val'))
Xte, yte = armar(pares_de('test'))
