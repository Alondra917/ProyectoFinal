# 6. tf.data y modelo (igual que el de prueba, con Rescaling dentro)
from tensorflow.keras import layers

aug = tf.keras.Sequential([layers.RandomFlip('horizontal'), layers.RandomRotation(0.05), layers.RandomZoom(0.1)])

def hacer_ds(X, y, entrenar):
    d = tf.data.Dataset.from_tensor_slices((X, y))
    if entrenar:
        d = d.shuffle(len(X), seed=SEED)
    d = d.batch(32).map(lambda a, b: (tf.cast(a, tf.float32), b))
    if entrenar and AUMENTAR:
        d = d.map(lambda a, b: (aug(a, training=True), b))
    return d.prefetch(tf.data.AUTOTUNE)

train_ds, val_ds = hacer_ds(Xtr, ytr, True), hacer_ds(Xva, yva, False)

base_model = tf.keras.applications.MobileNetV2(input_shape=(IMG, IMG, 3), include_top=False, weights=PESOS)
base_model.trainable = False

entrada = tf.keras.Input(shape=(IMG, IMG, 3))
x = layers.Rescaling(1. / 127.5, offset=-1)(entrada)      # la app pasa píxeles en [0, 255]
x = base_model(x, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.Dense(64, activation='relu')(x)
salida_modelo = layers.Dense(len(class_names), activation='softmax')(x)
model = tf.keras.Model(entrada, salida_modelo)

model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=1e-4),
              loss='sparse_categorical_crossentropy', metrics=['accuracy'])
model.summary()

# 7. Entrenar: se queda con los mejores pesos según la pérdida de validación
cb = [tf.keras.callbacks.EarlyStopping(monitor='val_loss', patience=5, restore_best_weights=True)]
history = model.fit(train_ds, validation_data=val_ds, epochs=EPOCAS_MAX, callbacks=cb)
model.save(f'{SALIDA}/modelo.keras')
print('Épocas entrenadas:', len(history.history['loss']),
      '| mejor val_accuracy:', round(max(history.history['val_accuracy']), 3))

# 8. Evaluación: precisión y recall por clase + matriz de confusión
import matplotlib.pyplot as plt
from sklearn.metrics import classification_report, confusion_matrix

def evaluar(X, y, titulo, exigir_recall=None):
    pred = model.predict(X.astype('float32'), batch_size=32, verbose=0).argmax(1)
    presentes = sorted(set(y.tolist()))
    print(f'=== {titulo}: {len(y)} fotos, exactitud global {(pred == y).mean():.3f} ===')
    print(classification_report(y, pred, labels=presentes, target_names=[class_names[i] for i in presentes], zero_division=0))
    cm = confusion_matrix(y, pred, labels=list(range(len(class_names))))
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.imshow(cm, cmap='Blues')
    ax.set_xticks(range(len(class_names))); ax.set_xticklabels(class_names, rotation=45, ha='right')
    ax.set_yticks(range(len(class_names))); ax.set_yticklabels(class_names)
    for i in range(len(class_names)):
        for j in range(len(class_names)):
            ax.text(j, i, cm[i, j], ha='center', va='center', color='black' if cm[i, j] < cm.max() / 2 else 'white')
    ax.set_xlabel('Predicha'); ax.set_ylabel('Real'); ax.set_title(titulo)
    plt.tight_layout(); plt.show()
    if exigir_recall is not None:
        for i in presentes:
            r = cm[i, i] / cm[i].sum()
            print(f'{class_names[i]:18s} recall {r:.2f}', 'OK' if r >= exigir_recall else 'NO CUMPLE')

