# 2. Configuración: cambia aquí las especies si decides otra
import requests, time

ESPECIES = {
    'Strongylocentrotus purpuratus': 'erizo_morado',
    'Zalophus californianus': 'lobo_marino',
    'Pachygrapsus crassipes': 'cangrejo_rayado',
}
PLACE_ID = 8501      #Baja California
MAX_OBS = 250        # observaciones (= fotos) máximas por especie
API = 'https://api.inaturalist.org/v1'

def get(url, params=None, intentos=3):
    for i in range(intentos):
        try:
            r = requests.get(url, params=params, timeout=30)
            if r.status_code == 200:
                return r
        except requests.RequestException:
            pass
        time.sleep(2 * (i + 1))
    raise RuntimeError(f'Falló la petición: {url}')

print('Lugar:', get(f'{API}/places/{PLACE_ID}').json()['results'][0]['display_name'])

# 3. Resolver cada especie por nombre exacto y contar observaciones disponibles
TAXON_IDS = {}
FILTROS = {'place_id': PLACE_ID, 'quality_grade': 'research', 'captive': 'false', 'photos': 'true'}

for cientifico in ESPECIES:
    res = get(f'{API}/taxa', {'q': cientifico, 'rank': 'species'}).json()['results']
    exacto = [t for t in res if t['name'] == cientifico]
    assert exacto, f'No se encontró {cientifico}'
    TAXON_IDS[cientifico] = exacto[0]['id']
    total = get(f'{API}/observations', {**FILTROS, 'taxon_id': exacto[0]['id'], 'per_page': 1}).json()['total_results']
    print(cientifico, '| id', exacto[0]['id'], '|', exacto[0].get('preferred_common_name'), '|', total, 'observaciones')

# 4. Descargar con paginación (reanudable)
import os, csv

INAT = f'{BASE}/inaturalist'
os.makedirs(INAT, exist_ok=True)
meta_path = f'{INAT}/metadata.csv'
campos = ['archivo', 'clase', 'taxon', 'obs_id', 'licencia', 'atribucion', 'url']
escribir_encabezado = not os.path.exists(meta_path)
meta = open(meta_path, 'a', newline='')
w = csv.DictWriter(meta, fieldnames=campos)
if escribir_encabezado:
    w.writeheader()

for cientifico, clase in ESPECIES.items():
    os.makedirs(f'{INAT}/{clase}', exist_ok=True)
    n = len(os.listdir(f'{INAT}/{clase}'))
    pagina = 1
    while n < MAX_OBS:
        res = get(f'{API}/observations', {**FILTROS, 'taxon_id': TAXON_IDS[cientifico],
                  'order_by': 'id', 'order': 'asc', 'per_page': 100, 'page': pagina}).json()['results']
        if not res:
            break
        for obs in res:
            if n >= MAX_OBS:
                break
            ruta = f"{INAT}/{clase}/{obs['id']}.jpg"
            if os.path.exists(ruta) or not obs.get('photos'):
                continue
            try:
                foto = obs['photos'][0]
                url = foto['url'].replace('square', 'medium')
                contenido = get(url).content
            except Exception as e:
                print('Error con la observación', obs['id'], e)
                continue
            with open(ruta, 'wb') as f:
                f.write(contenido)
            w.writerow({'archivo': ruta, 'clase': clase, 'taxon': cientifico, 'obs_id': obs['id'],
                        'licencia': foto.get('license_code'), 'atribucion': foto.get('attribution'), 'url': url})
            n += 1
            time.sleep(0.2)
        pagina += 1
        time.sleep(1)
    print(clase, n, 'fotos')

meta.close()

# 5. Revisión visual: 8 fotos al azar por clase (semilla fija)
